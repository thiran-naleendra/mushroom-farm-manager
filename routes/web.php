use App\Http\Controllers\RecipeController;
use App\Http\Controllers\SupplierController;
use App\Http\Controllers\UserController;
use Illuminate\Support\Facades\Route;

Route::middleware('guest')->group(function () {
    Route::get('/login', [AuthController::class, 'form'])->name('login');
    Route::post('/login', [AuthController::class, 'login'])->middleware('throttle:5,1');
    Route::post('/setup', [AuthController::class, 'setup'])->middleware('throttle:5,1')->name('setup');
});
Route::middleware(['auth', 'farm.timezone', 'active', 'auth.session'])->group(function () {
    Route::get('/reports/analytics', [AnalyticsController::class, 'index'])->name('analytics.index');
    Route::resource('expenses', ExpenseController::class)->except('show');
    Route::post('/expense-categories', [ExpenseController::class, 'category'])->name('expenses.categories');
    Route::get('/reports', [ExpenseController::class, 'reports'])->name('reports.index');
    Route::get('/reports/production', [ExpenseController::class, 'productionReport'])->name('reports.production');
    Route::post('/reports/harvests/{harvest}/cost', [ExpenseController::class, 'allocate'])->name('reports.harvest-cost');
    Route::get('/sales', [InvoiceController::class, 'index'])->name('invoices.index');
    Route::get('/sales/create', [InvoiceController::class, 'create'])->name('invoices.create');
    Route::get('/sales/legacy', [FarmController::class, 'index'])->defaults('section', 'sales')->name('sales.legacy');
    Route::post('/invoices', [InvoiceController::class, 'store'])->name('invoices.store');
    Route::get('/invoices/{invoice}', [InvoiceController::class, 'show'])->name('invoices.show');
    Route::get('/invoices/{invoice}/pdf', [InvoiceController::class, 'pdf'])->name('invoices.pdf');
    Route::get('/invoices/{invoice}/print', [InvoiceController::class, 'print'])->name('invoices.print');
    Route::post('/invoices/{invoice}/payments', [InvoiceController::class, 'payment'])->name('invoices.payments');
    Route::post('/invoices/{invoice}/returns', [InvoiceController::class, 'returnItems'])->name('invoices.returns');
    Route::post('/invoices/{invoice}/void', [InvoiceController::class, 'void'])->name('invoices.void');
    Route::resource('customers', CustomerController::class)->except('show');
    Route::get('/customers/{customer}', [CustomerController::class, 'show'])->withTrashed()->name('customers.show');
    Route::post('/customers/{customer}/balance', [CustomerController::class, 'adjust'])->name('customers.balance');
    Route::resource('products', ProductController::class)->except('show');
    Route::get('/packaging', [PackagingController::class, 'index'])->name('packaging.index');
    Route::post('/packaging', [PackagingController::class, 'store'])->name('packaging.store');
    Route::get('/packaging/{packaging}', [PackagingController::class, 'show'])->name('packaging.show');
    Route::get('/cultivation', [CultivationController::class, 'index'])->name('cultivation.index');
    Route::get('/cultivation/{batch}', [CultivationController::class, 'show'])->name('cultivation.show');
    Route::patch('/cultivation/{batch}', [CultivationController::class, 'update'])->name('cultivation.update');
    Route::get('/harvests', [HarvestController::class, 'index'])->name('harvests.index');
    Route::post('/harvests', [HarvestController::class, 'store'])->name('harvests.store');
    Route::resource('recipes', RecipeController::class)->except('show');
    Route::get('/production', [ProductionController::class, 'index'])->name('production.index');
    Route::get('/production/create', [ProductionController::class, 'create'])->name('production.create');
    Route::post('/production/preview', [ProductionController::class, 'preview'])->name('production.preview');
    Route::get('/production/confirm', [ProductionController::class, 'confirmation'])->name('production.confirm');
    Route::post('/production', [ProductionController::class, 'store'])->name('production.store');
    Route::get('/production/{batch}', [ProductionController::class, 'show'])->name('production.show');
    Route::patch('/production/{batch}/correct', [ProductionController::class, 'correct'])->name('production.correct');
    Route::post('/production/{batch}/void', [ProductionController::class, 'void'])->name('production.void');
    Route::resource('suppliers', SupplierController::class)->except('show');
    Route::get('/suppliers/{supplier}', [SupplierController::class, 'show'])->withTrashed()->name('suppliers.show');
    Route::get('/purchases', [PurchaseController::class, 'index'])->name('purchases.index');
    Route::get('/purchases/create', [PurchaseController::class, 'create'])->name('purchases.create');
    Route::post('/purchases', [PurchaseController::class, 'store'])->name('purchases.store');
    Route::get('/purchases/{purchase}', [PurchaseController::class, 'show'])->name('purchases.show');
    Route::post('/purchases/{purchase}/receive', [PurchaseController::class, 'receive'])->name('purchases.receive');
    Route::post('/purchases/{purchase}/payments', [PurchaseController::class, 'payment'])->name('purchases.payments');
    Route::post('/purchases/{purchase}/returns', [PurchaseController::class, 'returnItems'])->name('purchases.returns');
    Route::get('/inventory', [MaterialController::class, 'index'])->name('inventory.index');
    Route::get('/inventory/create', [MaterialController::class, 'create'])->name('inventory.create');
    Route::get('/inventory/options', [InventoryOptionController::class, 'index'])->name('inventory.options');
    Route::post('/inventory/options/{kind}', [InventoryOptionController::class, 'save'])->whereIn('kind', ['categories', 'units'])->name('inventory.options.store');
    Route::put('/inventory/options/{kind}/{option}', [InventoryOptionController::class, 'save'])->whereIn('kind', ['categories', 'units'])->whereNumber('option')->name('inventory.options.update');
    Route::post('/inventory', [MaterialController::class, 'store'])->name('inventory.store');
    Route::get('/inventory/{material}', [MaterialController::class, 'show'])->withTrashed()->name('inventory.show');
    Route::get('/inventory/{material}/edit', [MaterialController::class, 'edit'])->name('inventory.edit');
    Route::put('/inventory/{material}', [MaterialController::class, 'update'])->name('inventory.update');
    Route::delete('/inventory/{material}', [MaterialController::class, 'destroy'])->name('inventory.destroy');
    Route::post('/inventory/{material}/adjust', [MaterialController::class, 'adjust'])->name('inventory.adjust');
    Route::get('/settings', [FarmSettingsController::class, 'edit'])->name('settings.edit');
    Route::put('/settings', [FarmSettingsController::class, 'update'])->name('settings.update');
    Route::get('/farm/logo', [FarmSettingsController::class, 'logo'])->name('farm.logo');
    Route::get('/users', [UserController::class, 'index'])->name('users.index');
    Route::post('/users', [UserController::class, 'store'])->name('users.store');
    Route::get('/users/{user}/edit', [UserController::class, 'edit'])->name('users.edit');
    Route::put('/users/{user}', [UserController::class, 'update'])->name('users.update');
    Route::patch('/roles/{role}', [UserController::class, 'role'])->name('roles.update');
    Route::get('/', DashboardController::class)->name('dashboard');
    Route::post('/logout', [AuthController::class, 'logout'])->name('logout');
    Route::patch('/production/{batch}/stage', [FarmController::class, 'stage'])->name('production.stage');
    Route::get('/production/{batch}/label', [FarmController::class, 'label'])->name('production.label');
    Route::post('/{type}', [FarmController::class, 'store'])->whereIn('type', ['sales', 'expenses'])->name('records.store');
    Route::get('/{section}', [FarmController::class, 'index'])->whereIn('section', ['sales', 'expenses'])->name('farm.section');
});
